function output(itemId: string, text: string, authority: OutputState['authority']): OutputState {
  return {
    itemId,
    revision: 1,
    text,
    byteLength: utf8Length(text),
    isFinal: authority === 'AUTHORITATIVE_FINAL',
    authority,
    hasGap: authority === 'FINAL_OUTPUT_UNAVAILABLE',
  }
}

